function serialize(obj) {
  return JSON.stringify(obj, null, 2)
    .replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, '$1:')
    .replace(/"/g, "'")
    .replace(/\\'/g, "\\'");
}

// JSON.stringify with single quotes for JS is messy - better use util or just write module.exports properly
function writeModule(file, data) {
  fs.writeFileSync(file, 'module.exports = ' + JSON.stringify(data, null, 2) + ';\n');
}

